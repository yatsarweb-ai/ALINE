import {chromium} from 'playwright-core';
const baseUrl=process.argv[2]||'http://localhost:3000';
const browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'});
const errors=[];
const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
page.on('pageerror',e=>errors.push(e.message));
await page.goto(baseUrl,{waitUntil:'networkidle'});
const sectionOrder=await page.locator('main.home-shell section').evaluateAll(elements=>elements.map(element=>element.classList[0]));
if(sectionOrder.join(',')!=='hero,collections,cake-banner,testimonials,photo-mosaic,event-quote,ideas,newsletter')throw new Error(`Orden de secciones incorrecto: ${sectionOrder}`);
const activeReview=page.locator('.testimonial-card[aria-hidden="false"]');
const firstReview=await activeReview.locator('p').innerText();
await page.getByRole('button',{name:'Reseña siguiente'}).click();
if(await activeReview.locator('p').innerText()===firstReview)throw new Error('Carrusel de reseñas no cambia');
if(!(await activeReview.innerText()).includes('Reseña demostrativa'))throw new Error('Falta identificar reseña demostrativa');
const firstCategoryPosition=await page.locator('.category-viewport').evaluate(element=>element.scrollLeft);
await page.getByRole('button',{name:'Categorías siguientes'}).click();
await page.waitForTimeout(180);
if(await page.locator('.category-viewport').evaluate(element=>element.scrollLeft)===firstCategoryPosition)throw new Error('Navegación de categorías no cambia');
if(await page.locator('.mosaic-cell').count()!==6)throw new Error('Galería sin selección curada de seis fotos');
for(const route of ['/colecciones','/producto/tradicional','/personalizados','/eventos','/nosotros','/carrito']){
 const response=await page.goto(baseUrl+route,{waitUntil:'networkidle'});
 if(response.status()!==200)throw new Error(`${route}: HTTP ${response.status()}`);
}
await page.goto(baseUrl+'/colecciones',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Brigadeiros',exact:true}).click();
if(await page.locator('.product-card').count()!==7)throw new Error('Filtro brigadeiros incorrecto');
await page.getByRole('button',{name:'Agregar al carrito'}).first().click();
await page.goto(baseUrl+'/carrito',{waitUntil:'networkidle'});
if(!(await page.locator('.cart-summary').innerText()).includes('$2.00'))throw new Error('Subtotal incorrecto');
await page.reload({waitUntil:'networkidle'});
if(await page.locator('.cart-item').count()!==1)throw new Error('El carrito no persiste');
await page.locator('.cart-controls button').last().click();
if(!(await page.locator('.cart-summary').innerText()).includes('$4.00'))throw new Error('Cantidad incorrecta');
await page.getByRole('button',{name:'Consultar pedido'}).click();
if(!(await page.locator('.contact-notice').innerText()).includes('no está configurado'))throw new Error('Falta estado de WhatsApp');
await page.goto(baseUrl+'/eventos',{waitUntil:'networkidle'});
await page.locator('input[name="nombre"]').fill('Cliente de prueba');
await page.locator('select[name="tipo"]').selectOption({label:'Boda'});
await page.locator('input[name="fecha"]').fill('2026-12-15');
await page.locator('input[name="cantidad"]').fill('40');
await page.locator('input[name="tematica"]').fill('Menta y chocolate');
await page.locator('textarea[name="comentarios"]').fill('Entrega en Caracas');
await page.getByRole('button',{name:'Enviar consulta'}).click();
const quote=await page.locator('.form-notice').innerText();
if(!quote.includes('WhatsApp todavía no está configurado'))throw new Error('Falta estado del formulario');
const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto(baseUrl,{waitUntil:'networkidle'});
const width=await mobile.evaluate(()=>({inner:innerWidth,scroll:document.documentElement.scrollWidth}));
if(width.scroll>width.inner)throw new Error(`Scroll horizontal móvil: ${JSON.stringify(width)}`);
await mobile.getByRole('button',{name:'Abrir menú'}).click();
if(!(await mobile.getByRole('navigation').getByRole('link',{name:'Colecciones'}).isVisible()))throw new Error('Menú móvil no abre');
for(const width of [320,768]){await mobile.setViewportSize({width,height:844});await mobile.reload({waitUntil:'networkidle'});const size=await mobile.evaluate(()=>({inner:innerWidth,scroll:document.documentElement.scrollWidth}));if(size.scroll>size.inner)throw new Error(`Scroll horizontal a ${width} px: ${JSON.stringify(size)}`)}
if(errors.length)throw new Error(`Errores de página: ${errors.join('; ')}`);
console.log('OK: flujo vertical, carruseles, rutas, filtros, carrito, persistencia, cantidades, cotización, menú móvil y anchos de 320, 390 y 768 px.');
await browser.close();

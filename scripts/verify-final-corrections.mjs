import {chromium} from 'playwright-core';

const baseUrl=process.argv[2]||'http://localhost:3000';
const browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.clock.install();
await page.goto(baseUrl,{waitUntil:'networkidle'});
await page.clock.pauseAt(new Date());
const active=page.locator('.testimonial-card[aria-hidden="false"] p');
const first=await active.innerText();
await page.clock.runFor(7000);
if(await active.innerText()!==first)throw new Error('La reseña cambió antes de los 8 segundos');
await page.clock.runFor(1200);
if(await active.innerText()===first)throw new Error('La reseña no cambió a los 8 segundos');
await page.locator('.testimonial-slider').hover();
const paused=await active.innerText();
await page.clock.runFor(8500);
if(await active.innerText()!==paused)throw new Error('El carrusel avanzó durante hover');
await page.mouse.move(0,0);
await page.clock.runFor(8000);
if(await active.innerText()===paused)throw new Error('El carrusel no reanudó tras hover');
await page.getByRole('button',{name:'Reseña siguiente'}).click();
await page.clock.runFor(500);
if(await active.innerText()!==first)throw new Error('El carrusel no volvió a la primera reseña');
await page.goto(baseUrl+'/colecciones?categoria=Brigadeiros',{waitUntil:'networkidle'});
if(await page.locator('.catalog-grid .brigadeiro-card').count()!==7)throw new Error('Tarjetas de brigadeiros incompletas');
if(await page.locator('.catalog-grid .brigadeiro-card .product-description').count()!==7)throw new Error('Faltan descripciones');
await page.screenshot({path:'preview-brigadeiros-desktop.png',fullPage:true});
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1,reducedMotion:'reduce'});
await mobile.goto(baseUrl+'/colecciones?categoria=Brigadeiros',{waitUntil:'networkidle'});
await mobile.screenshot({path:'preview-brigadeiros-mobile.png',fullPage:true});
const logoBackground=await mobile.locator('.site-header .header-logo img').evaluate(image=>getComputedStyle(image).backgroundColor);
if(logoBackground!=='rgba(0, 0, 0, 0)')throw new Error(`Logo con fondo: ${logoBackground}`);
for(const current of [page,mobile]){const overflow=await current.evaluate(()=>document.documentElement.scrollWidth>innerWidth);if(overflow)throw new Error('Scroll horizontal en catálogo')}
await mobile.goto(baseUrl,{waitUntil:'networkidle'});
const mobileFirst=await mobile.locator('.testimonial-card[aria-hidden="false"] p').innerText();
await mobile.locator('.testimonial-slider').evaluate(element=>{const start=new Touch({identifier:1,target:element,clientX:280,clientY:100});const end=new Touch({identifier:1,target:element,clientX:90,clientY:100});element.dispatchEvent(new TouchEvent('touchstart',{touches:[start],changedTouches:[start],bubbles:true}));element.dispatchEvent(new TouchEvent('touchend',{touches:[],changedTouches:[end],bubbles:true}))});
if(await mobile.locator('.testimonial-card[aria-hidden="false"] p').innerText()===mobileFirst)throw new Error('El gesto táctil no cambió la reseña');
console.log('OK: 8 segundos, pausa, ciclo completo, gesto táctil, siete brigadeiros, logo transparente y catálogo responsive.');
await browser.close();
